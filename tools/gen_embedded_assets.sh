#!/usr/bin/env bash
# tools/gen_embedded_assets.sh <public_dir> <build_dir>
# Regenerates build/embedded_assets.cpp from every file under public/.
# Run automatically by `make` — you shouldn't need to invoke this by hand.
set -euo pipefail

PUBLIC_DIR="${1:-public}"
BUILD_DIR="${2:-build}"
OUT="$BUILD_DIR/embedded_assets.cpp"

mkdir -p "$BUILD_DIR"

mime_for() {
  case "$1" in
    *.html) echo "text/html; charset=utf-8" ;;
    *.css)  echo "text/css; charset=utf-8" ;;
    *.js)   echo "application/javascript; charset=utf-8" ;;
    *.json) echo "application/json; charset=utf-8" ;;
    *.svg)  echo "image/svg+xml" ;;
    *.png)  echo "image/png" ;;
    *.ico)  echo "image/x-icon" ;;
    *)      echo "application/octet-stream" ;;
  esac
}

{
  echo "// AUTO-GENERATED by tools/gen_embedded_assets.sh — do not edit."
  echo "// Regenerated automatically by make whenever public/ changes."
  echo "#include \"embedded_assets.h\""
  echo "#include <unordered_map>"
  echo
} > "$OUT"

entries=()

while IFS= read -r -d '' file; do
  rel="${file#"$PUBLIC_DIR"/}"
  sym="asset_$(echo "$rel" | sed 's/[^A-Za-z0-9]/_/g')"

  raw="$(xxd -i "$file")"
  orig_name="$(head -1 <<<"$raw" | sed -E 's/unsigned char ([A-Za-z0-9_]+)\[\].*/\1/')"
  echo "$raw" | sed "s/${orig_name}/${sym}/g" >> "$OUT"
  echo >> "$OUT"

  mime="$(mime_for "$rel")"
  entries+=("    {\"/${rel}\", {${sym}, ${sym}_len, \"${mime}\"}},")
done < <(find "$PUBLIC_DIR" -type f -print0 | sort -z)

{
  echo "static const std::unordered_map<std::string, EmbeddedAsset> kEmbeddedAssets = {"
  for e in "${entries[@]}"; do echo "$e"; done
  echo "};"
  echo
  echo "const EmbeddedAsset* find_embedded_asset(const std::string& path) {"
  echo "    auto it = kEmbeddedAssets.find(path);"
  echo "    return it == kEmbeddedAssets.end() ? nullptr : &it->second;"
  echo "}"
} >> "$OUT"

echo "Generated $OUT (${#entries[@]} assets)"
